let _uiLang = "en";
let _vsUiLang = "en";

function t(key, params) {
    let s = (I18N[_uiLang] && I18N[_uiLang][key]) ?? I18N.en[key] ?? key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
    return s;
}

function applyI18n(root) {
    root = root || document;
    const fill = (attr, apply) => root.querySelectorAll(`[${attr}]`).forEach(el => apply(el, t(el.getAttribute(attr))));
    fill("data-i18n", (el, s) => { el.textContent = s; });
    fill("data-i18n-html", (el, s) => { el.innerHTML = s; });
    fill("data-i18n-title", (el, s) => { el.title = s; });
    fill("data-i18n-placeholder", (el, s) => { el.placeholder = s; });
    fill("data-i18n-aria-label", (el, s) => { el.setAttribute("aria-label", s); });
}

function getUiLanguagePref() {
    try { return localStorage.getItem("uiLanguage") || "auto"; } catch (_) { return "auto"; }
}

function refreshUiLanguage() {
    const pref = getUiLanguagePref();
    const lang = pref === "en" || pref === "tr" ? pref : (_vsUiLang === "tr" ? "tr" : "en");
    if (lang === _uiLang && document.documentElement.lang === lang) return;
    _uiLang = lang;
    document.documentElement.lang = lang;
    applyI18n(document);
    if (typeof onUiLanguageChanged === "function") onUiLanguageChanged();
}

function setUiLanguage(pref) {
    try { localStorage.setItem("uiLanguage", pref); } catch (_) { }
    refreshUiLanguage();
    if (typeof syncAppearanceToHost === "function") syncAppearanceToHost();
}

